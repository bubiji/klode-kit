"""Helpers for the WI-34 adopt tests: a synthetic pre-klode-kit klode library, built with the real ``klode`` CLI.

``old_kb(root, ...)`` makes what the older scripts left behind (klode 0.5.0 layout): ``library.toml`` with id / name /
description / shelves, ``library/<shelf>/<id>.txt`` (the aurora chapters, spread over the shelves), the scaffold of
``klode build --stamp`` in ``library/cards`` and the cards in one of three shapes:

- ``content``: ``cards_content/<id>.md`` (the same aliases / ``## Thin`` / ``## Full`` format klode-kit uses);
- ``scaffold``: no ``cards_content/``; the card text sits below the marker of ``library/cards/<id>.md``;
- ``both``: both, and the copy in ``library/cards`` is a different text (``cards_content`` has to win).

Cards in ``drop`` are left unwritten (the klode stub), optionally with a desk (``src/desk.json`` + holdout) and its
syntheses. Text is synthetic; nothing here touches a real library.
"""

from __future__ import annotations

import hashlib
import re
import subprocess
from pathlib import Path
from typing import Sequence

from _support import build_fx as B
from _support import desk_fx as DX
from _support.write_card_fx import content as card_content
from klode_kit.build import init_kb, write_card

CARDS = ("ch01", "ch02", "ch03")
OLD_ID = "old-aurora"


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def shelf_of(shelves: Sequence[str], cid: str) -> str:
    return shelves[CARDS.index(cid) % len(shelves)]


def card_text(cid: str) -> str:
    return card_content(DX.ANCHORS[cid], DX.ALIASES[cid])


def _klode(old: Path, *args: str) -> None:
    res = subprocess.run([B.klode_exe(), "-c", str(old / "library.toml"), *args], capture_output=True, text=True,
                         timeout=300)
    assert res.returncode == 0, res.stdout + res.stderr


def old_kb(root: Path, *, shelves: Sequence[str] = ("alpha", "beta", "gamma"), cards: str = "content",
           drop: Sequence[str] = (), desk: bool = False, frameworks: bool | None = None,
           bibliography: bool = True) -> Path:
    """Build the old library at ``root`` (created); returns ``root``. ``frameworks`` defaults to ``desk``."""
    frameworks = desk if frameworks is None else frameworks
    assert cards in ("content", "scaffold", "both")
    res = subprocess.run([B.klode_exe(), "init", *[a for s in shelves for a in ("--shelf", s)], str(root)],
                         capture_output=True, text=True, timeout=300)
    assert res.returncode == 0, res.stdout + res.stderr
    init_kb.init_kb(root, OLD_ID, shelves=list(shelves), name="Old Aurora Library",
                    description="Aurora text, three chapters, built by the old scripts")
    for cid in CARDS:
        (root / "library" / shelf_of(shelves, cid) / f"{cid}.txt").write_bytes(DX.CH[cid].encode("utf-8"))
    if bibliography:
        rows = "".join(f"| The Aurora Kettle {c} | library/{shelf_of(shelves, c)}/{c}.txt | chapter |\n"
                       for c in CARDS)
        bib = root / "library" / "BIBLIOGRAPHY.md"
        bib.write_text(bib.read_text(encoding="utf-8") + rows, encoding="utf-8")
    _klode(root, "build", "--stamp")
    for cid in CARDS:
        if cid in drop:
            continue
        stub = root / "library" / "cards" / f"{cid}.md"
        if cards in ("content", "both"):
            (root / "cards_content").mkdir(exist_ok=True)
            (root / "cards_content" / f"{cid}.md").write_text(card_text(cid), encoding="utf-8")
        if cards in ("scaffold", "both"):
            text = card_text(cid) if cards == "scaffold" else card_text(cid).replace("copper shell", "old copy", 1)
            aliases, body = write_card.parse_content(text) or ([], "")
            stub.write_text(write_card.render(stub.read_text(encoding="utf-8"), aliases, body), encoding="utf-8")
    toml = root / "library.toml"
    if frameworks:
        t = toml.read_text(encoding="utf-8")
        toml.write_text(re.sub(r"(\[frameworks\][^\n]*\n(?:[^\[]*?))enabled = false", r"\1enabled = true", t, count=1,
                               flags=re.S), encoding="utf-8")
    if desk:
        (root / "src").mkdir(exist_ok=True)
        B.desk_files(root / "src")
        syn = root / "library" / "frameworks" / "_syntheses"
        B.syntheses(syn)
        (syn / "_diagnostics.md").write_text("# old diagnostics (generated by the old scripts)\n", encoding="utf-8")
    return root


def tree_hash(root: Path) -> dict:
    """Everything below ``root``: kind, content hash, mtime (the old tree must come out byte- and mtime-identical)."""
    return {"": B.snapshot(root)}


def adopt(project: Path, tmp: Path, old: Path, *args: str, kb: str = "kb/demo-adopt",
          extra_env: dict | None = None):
    return B.build(project, tmp, "--adopt", str(old), "--kb", kb, *args, extra_env=extra_env)


def by_step(build_dir: Path) -> dict:
    return {s["step"]: s for s in B.receipt(build_dir)["steps"]}


def claude_calls(env: dict) -> int:
    log = Path(env["KLODE_KIT_FAKE_LOG"])
    return log.read_text(encoding="utf-8").count('"tool": "claude"') if log.exists() else 0


def fake_env(tmp: Path) -> dict:
    """The fake ``claude`` call log of this test (no scenario: any call would also fail the build)."""
    return {"KLODE_KIT_FAKE_LOG": str(tmp / "claude-calls.jsonl")}


def cards_dir(dest: Path, ids: Sequence[str] = CARDS, *, variant: str | None = None) -> Path:
    """A ``--cards-from`` directory: ``<id>.md`` in the cards_content format (``variant``: a marker alias)."""
    dest.mkdir(parents=True, exist_ok=True)
    for cid in ids:
        aliases = list(DX.ALIASES[cid]) + ([variant] if variant else [])
        (dest / f"{cid}.md").write_text(card_content(DX.ANCHORS[cid], aliases), encoding="utf-8")
    return dest


__all__ = ["old_kb", "adopt", "by_step", "card_text", "cards_dir", "claude_calls", "fake_env", "tree_hash", "sha",
           "CARDS", "OLD_ID", "shelf_of"]
