"""WI-06a (WI-05b main-session decision): the sender's G2 real-call gate.

Rule (shared with the execution bridge, ``klode_kit.gate``): when the ``claude`` / ``codex`` that ``send`` would
start - resolved on the invocation PATH - is neither the replay fake in this repository's ``tests/fakes/bin`` nor a
fake generated by ``tests/_support/send_fake.FakeCloud`` (its front carries ``klode_kit.gate.TEST_FAKE_MARKER``),
``send`` refuses unless ``KLODE_KIT_REAL == "1"`` AND ``KLODE_KIT_GATE_ACK`` is ``G2-<yyyymmdd>`` (a calendar date):
``SendRefused`` exit 61, reason ``gate_closed``; the CLI exits 61. Zero calls - not even the review's
``--version`` probe.

"Zero calls" is observed: the pseudo-real CLI is ``FakeCloud(pseudo_real=True)`` - the recording executable
without the marker - so its log shows every start; the positive control proves the same harness records a call
once the gate is open.

Law (S4): for every environment that is not (REAL=1 and a valid G2 ack), a non-fake CLI is started zero times;
marked fakes are never gated. The bridge keeps its own rule (only ``tests/fakes/bin``; 00d2 cases unchanged).
"""

