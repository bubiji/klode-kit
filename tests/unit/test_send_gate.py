def test_cli_exit_61_zero_calls(pseudo, monkeypatch):
    """The CLI entry: gate closed + pseudo-real first on PATH -> exit 61, G2 named on stderr, log empty."""
    iso = pseudo.iso("claude")
    env = base_env({"PATH": pseudo.env["PATH"], "HOME": str(pseudo.home), "TMPDIR": str(pseudo.systmp),
                    "LANG": "C.UTF-8"}, drop=("KLODE_KIT_REAL", "KLODE_KIT_GATE_ACK"))
    data = FIXTURE_PNG.read_bytes()
    res = subprocess.run([sys.executable, "-m", "klode_kit.ocr.send", "--route", "claude", "--project",
                          str(pseudo.project), "--receipt-dir", str(pseudo.receipts), "--isolation-receipt", str(iso),
                          "--routes-state", str(pseudo.state), str(FIXTURE_PNG), sha256(data)],
                         env=env, capture_output=True, timeout=60)
    assert res.returncode == 61, res.stderr.decode()
    assert b"G2" in res.stderr
    assert pseudo.fake.calls() == []


ACKS = st.one_of(
    st.text(alphabet=st.characters(blacklist_characters="\x00"), max_size=14),  # env values cannot hold NUL (user-approved 2026-10-23)
    st.builds(lambda d: f"G2-{d}", st.text(alphabet="0123456789", min_size=0, max_size=10)),
    st.sampled_from([VALID_ACK, "G2-20260229", "G2-20240229"]),
)
REALS = st.one_of(st.none(), st.sampled_from(["0", "1", "true", "yes", " 1", "1 ", ""]))


@settings(max_examples=60, deadline=None, suppress_health_check=[HealthCheck.function_scoped_fixture])
@given(real=REALS, ack=st.one_of(st.none(), ACKS))
def test_gate_law_zero_calls_unless_open(pseudo, monkeypatch, real, ack):
    """S4 law: a non-fake CLI is started iff REAL == '1' and the ack is G2-<valid yyyymmdd>; otherwise exit 61
    and zero calls. (Open cases only check the refusal is absent; they are not run here - see the control.)"""
    import datetime as _dt
    import re

    pseudo.iso("claude")
    values = {}
    if real is not None:
        values["KLODE_KIT_REAL"] = real
    if ack is not None:
        values["KLODE_KIT_GATE_ACK"] = ack
    _set_gate(monkeypatch, values)
    m = re.fullmatch(r"G2-([0-9]{8})", ack or "")
    valid_date = False
    if m and (ack or "").isascii():
        try:
            _dt.datetime.strptime(m.group(1), "%Y%m%d")
            valid_date = True
        except ValueError:
            pass
    open_ = real == "1" and valid_date and not (ack or "").endswith("\n")
    before = len(pseudo.fake.calls())
    if open_:
        res = pseudo.send("claude")
        assert res.receipt["reason"] != "gate_closed"
        assert len(pseudo.fake.model_calls()) >= 1
    else:
        with pytest.raises(S.SendRefused) as info:
            pseudo.send("claude")
        assert (info.value.exit_code, info.value.reason) == (61, "gate_closed")
        assert len(pseudo.fake.calls()) == before


def test_bridge_still_gates_generated_fakes(tmp_path, monkeypatch):
    """Bridge behaviour unchanged (00d2): only tests/fakes/bin is exempt - a marked FakeCloud claude is still
    refused by the bridge with the gate closed, and nothing is started."""
    fake = FakeCloud(tmp_path / "fake")
    monkeypatch.setenv("PATH", os.pathsep.join([str(fake.bin), "/usr/bin", "/bin"]))
    _set_gate(monkeypatch, {"KLODE_KIT_REAL": "0"})
    build = tmp_path / "builds" / "b-20261023-0001"
    build.mkdir(parents=True)
    task = bridge.Task(task_id="t-001", build_dir=build, card="cards_content/c001.md", instructions="x")
    with pytest.raises(bridge.BridgeGateClosed):
        bridge.run([task], bridge.Options.from_config(load(), max_rounds=1))
    assert fake.calls() == []
